// Web-app oriented downloads: a Tailwind CSS v4 theme (tokens.tailwind.css) and AI rules (design-rules.md).
// Both are built from the brand's palette plus the app color roles in roles.mjs, so an AI picks colors by purpose
// (bg-app-surface, text-app-danger ...) instead of hard-coding hex values or Tailwind's default palette.
import { downloadView, fontRoles, cssSafe, thaiMinLh } from './downloads.mjs';

// Tailwind v4's default type scale (rem); text-sm etc. read --text-<size>--line-height, which is what we override for Thai
const TW_SIZES = { xs: 0.75, sm: 0.875, base: 1, lg: 1.125, xl: 1.25, '2xl': 1.5, '3xl': 1.875, '4xl': 2.25, '5xl': 3, '6xl': 3.75, '7xl': 4.5, '8xl': 6, '9xl': 8 };
import { deriveRoles } from './roles.mjs';

const px = (v) => { const n = parseFloat(v); return Number.isFinite(n) && /px$/.test(String(v)) ? n : NaN; };

/** Radius token whose size is closest to `target` px (falls back to a plain Tailwind class name). */
const radiusKey = (b, target, fallback) => {
  const c = Object.entries(b.tokens.rounded).filter(([, v]) => typeof v === 'string' && px(v) > 0 && px(v) < 100).sort((a, d) => Math.abs(px(a[1]) - target) - Math.abs(px(d[1]) - target))[0];
  return c ? c[0] : fallback;
};

/** tokens.tailwind.css: a Tailwind CSS v4 @theme block so brand and app colors become utilities. */
export function tailwindCss(b0) {
  const b = downloadView(b0), roles = deriveRoles(b), fr = fontRoles(b);
  const L = [`/* ${b.name} - Tailwind CSS v4 theme (generated by DESIGN.md Hub, for learning)`,
    ' * Setup: in your main CSS file, after  @import "tailwindcss";  add  @import "./tokens.tailwind.css";',
    ' * Brand colors become utilities (bg-primary, text-ink, border-hairline ...).',
    ' * App roles become utilities: bg-app-page, bg-app-surface, bg-app-surface-muted, text-app-text, text-app-text-muted,',
    ' *   border-app-border, bg-app-accent, bg-app-accent-soft, text-app-danger, bg-app-danger-soft, border-app-danger-border ...',
    ' * Keep tokens.css as well if you use the --text-* / --space-* variables or the .ds-* component classes. */',
    '',
    '/* OPTIONAL strict mode: removes the default Tailwind palette so bg-red-500 / text-slate-600 no longer exist and only',
    ' * the colors below do. Uncomment this block and keep it ABOVE the brand @theme block.',
    '@theme {',
    '  --color-*: initial;',
    '  --color-white: #ffffff;',
    '  --color-black: #000000;',
    '}',
    '*/',
    '',
    '@theme {'];
  for (const [k, v] of Object.entries({ ...b.tokens.colors, ...b.proseColors })) if (cssSafe(v)) L.push(`  --color-${k}: ${cssSafe(v)};`);
  L.push('', '  /* app roles: choose colors by purpose */');
  for (const r of roles) L.push(`  --color-app-${r.key}: ${r.value};`);
  const rad = Object.entries(b.tokens.rounded).filter(([, v]) => typeof v === 'string' && cssSafe(v));
  const radiusVal = (target, fallback) => { const k = radiusKey(b, target, ''); return k ? b.tokens.rounded[k] : fallback; };
  L.push('', '  /* brand-independent radius aliases: rounded-control (buttons, inputs), rounded-card (cards, panels, modals) */',
    `  --radius-control: ${cssSafe(radiusVal(8, '8px')) || '8px'};`, `  --radius-card: ${cssSafe(radiusVal(12, '12px')) || '12px'};`);
  if (rad.length) { L.push('', '  /* radius: rounded-<name> */'); for (const [k, v] of rad) L.push(`  --radius-${k}: ${cssSafe(v)};`); }
  L.push('', '  /* fonts: font-display, font-body ... (free substitutes, see the tokens.css header) */');
  for (const r of fr) L.push(`  --font-${r.var}: ${r.stack};`);
  L.push('}');
  // Tailwind's text-sm / text-xl set a fixed Latin line-height and tracking-* / uppercase are easy to add, none of which suit Thai.
  L.push('', '/* Thai content (<html lang="th">): taller line-height for every text-* size, no letter-spacing, no uppercase.',
    ' * Plain CSS outside @theme, so it also beats utilities such as tracking-wide and uppercase. */',
    ':root:lang(th) {');
  for (const [k, rem] of Object.entries(TW_SIZES)) L.push(`  --text-${k}--line-height: ${thaiMinLh(rem * 16)};`);
  L.push('}', 'html:lang(th) { line-height: 1.7; }', ':lang(th) [class*="tracking-"] { letter-spacing: normal; }', ':lang(th) .uppercase { text-transform: none; }');
  return L.join('\n') + '\n';
}

/** Copy-paste setup for a Tailwind v4 app driven by Claude Code (shown on the brand page). */
export function appStart(b0) {
  const b = downloadView(b0), roles = deriveRoles(b);
  const has = (k) => roles.some((r) => r.key === k);
  return `/* 1) src/index.css */
@import "tailwindcss";
@import "../design/tokens.tailwind.css";   /* bg-app-surface, text-app-danger, bg-primary ... */
@import "../design/tokens.css";            /* --app-* variables, --text-* sizes, .ds-* components */

# 2) CLAUDE.md  (Claude Code loads it every session)
@design/design-rules.md

<!-- then ask: "build the settings page with a sidebar, a table and a form" -->
<div class="bg-app-page text-app-text">
  <div class="${has('surface') ? 'bg-app-surface border border-app-border' : 'border'} rounded-lg p-4">...</div>
  <p class="bg-app-danger-soft border border-app-danger-border text-app-danger">...</p>
</div>`;
}

/** design-rules.md: short imperative rules for an AI coding tool (Claude Code loads it through an @import in CLAUDE.md). */
export function designRules(b0) {
  const b = downloadView(b0), roles = deriveRoles(b);
  // brand-independent aliases (defined in tokens.tailwind.css), so the same markup works whatever the brand names its radii
  const card = 'card', ctl = 'control';
  const fonts = fontRoles(b).map((x) => `\`font-${x.var}\``).join(', ');
  const nChart = roles.filter((x) => x.key.startsWith('chart-')).length;
  const table = roles.map((x) => `| \`app-${x.key}\` | \`bg-app-${x.key}\` \`text-app-${x.key}\` \`border-app-${x.key}\` | \`var(--app-${x.key})\` | ${x.value}${x.ref ? ` (= \`${x.ref}\`)` : ''} | ${x.note} |`).join('\n');
  const palette = Object.entries(b.tokens.colors).filter(([, v]) => cssSafe(v)).map(([k, v]) => `\`${k}\` ${v}`).join(' · ');
  return `# ${b.name} design rules (generated by DESIGN.md Hub)

Follow these rules whenever you build or change UI in this project. To load them every session, add this line to the project's CLAUDE.md (adjust the path to where you saved the files):

\`@design/design-rules.md\`

Files kept next to this one: \`DESIGN.md\` (the written design system: intent, do/don't), \`tokens.css\` (CSS variables and \`.ds-*\` component classes), \`tokens.tailwind.css\` (Tailwind CSS v4 theme: \`@import "./tokens.tailwind.css";\` after \`@import "tailwindcss";\`). If values differ, \`tokens.css\` wins.

## Hard rules

1. **Never write a color value** (\`#hex\`, \`rgb()\`, \`bg-[#...]\`) and **never use Tailwind's default palette** (\`red-500\`, \`emerald-600\`, \`slate-*\`, \`gray-*\`, \`zinc-*\` ...). Use the \`app-*\` roles below, or a brand color from the palette list.
2. **Choose a color by its purpose**, not by how it looks: page / surface / border / text for structure, \`accent\` for the primary action, \`danger\` \`success\` \`warning\` \`info\` for states, \`chart-1..${nChart}\` for data series.
3. **A status is always three classes together**: \`bg-app-<status>-soft border border-app-<status>-border text-app-<status>\` (alerts, badges, callouts). Never use a status color as a page or card background.
4. **Use neutrals in layers**, not one gray: \`app-page\` then \`app-surface\` (cards) then \`app-surface-muted\` (table header, sidebar, hover), with \`app-border\` for outlines and \`app-border-subtle\` for lines inside a card.
5. **One accent per screen area.** \`app-accent\` is for the single most important action. A selected state uses \`app-accent-soft\` with \`app-accent-border\`, not a second bright color.
6. **If you need a color that is not listed**, do not invent one: reuse the closest role or ask. For a tint use \`color-mix(in srgb, var(--app-accent) 10%, var(--app-page))\`.
7. **Fonts:** ${fonts} (tokens.css lists the substitutes). For Thai content set \`<html lang="th">\`: tokens.tailwind.css then raises the line-height of every \`text-*\` size (1.7 up to 16px, 1.5 up to 24px, 1.4 up to 32px, 1.3 above) and turns off \`tracking-*\` and \`uppercase\` for Thai, so keep using the normal \`text-sm\` / \`text-xl\` classes. Do not set \`leading-*\` on Thai text unless you need a looser value.
8. **Radius:** \`rounded-${ctl}\` for controls (buttons, inputs), \`rounded-${card}\` for cards and panels, \`rounded-full\` only for pills and avatars.

## Color roles

| Role | Tailwind | CSS variable | Value | Use for |
|---|---|---|---|---|
${table}

Brand palette (also utilities, e.g. \`bg-primary\`): ${palette}

## Patterns

- Card: \`bg-app-surface border border-app-border rounded-${card} p-4\`
- Primary button: \`bg-app-accent text-app-on-accent hover:bg-app-accent-hover disabled:bg-app-accent-disabled rounded-${ctl} px-4 py-2\`
- Secondary button: \`bg-app-surface text-app-text border border-app-border-strong hover:bg-app-surface-muted rounded-${ctl}\`
- Input: \`bg-app-surface text-app-text border border-app-border-strong placeholder:text-app-text-subtle focus:outline-none focus:ring-2 focus:ring-app-focus rounded-${ctl}\`
- Table: header \`bg-app-surface-muted text-app-text-muted border-b border-app-border\`; rows \`border-b border-app-border-subtle\`; selected row \`bg-app-accent-soft\`
- Navigation item: idle \`text-app-text-muted hover:bg-app-surface-muted\`; active \`bg-app-accent-soft text-app-accent\`
- Alert: \`bg-app-danger-soft border border-app-danger-border text-app-danger rounded-${ctl} p-3\` (same shape for success, warning, info)
- Empty state: icon and title \`text-app-text-muted\`, hint \`text-app-text-subtle\`, optional \`bg-app-surface-muted\` panel
- Link: \`text-app-link hover:underline\`
- Chart series: \`chart-1\` first, then \`chart-2\` and so on in order; do not reuse the danger color for an ordinary series.
`;
}
